function photo(file: string, author: string, license: keyof typeof licenses, width: number, height: number, en: string, ru: string) {
  return {
    title: file.slice(0, file.lastIndexOf('.')),
    source: `https://commons.wikimedia.org/wiki/${encodeURIComponent(`File:${file.replaceAll(' ', '_')}`)}`,
    author, license, licenseUrl: licenses[license], width, height,
    alt: { en, ru } as Readonly<Record<string, string>> & { en: string },
  }
}

